/// A URI or relative reference (RFC 3986, TypeBox `IsUriReference`).
pub(super) fn is_uri_reference(value: &str) -> bool {
	URI_REFERENCE.find(value).is_some()
}

static URI_TEMPLATE: LazyLock<Regex> = LazyLock::new(|| {
	pattern(
		concat!(
			r#"^(?:(?:[^\x00-\x20"<>%\\^`{|}\x7f]|%[0-9a-f]{2})|\{[+#./;?&=,!@|]?(?:[a-z0-9_]|%[0-9a-f]{2"#,
			r#"})+(?:\.(?:[a-z0-9_]|%[0-9a-f]{2})+)*(?::[1-9]\d{0,3}|\*)?(?:,(?:[a-z0-9_]|%[0-9a-f]{2})+("#,
			r#"?:\.(?:[a-z0-9_]|%[0-9a-f]{2})+)*(?::[1-9]\d{0,3}|\*)?)*\})*$"#,
		),
		"i",
	)
});

/// A URI template (RFC 6570, TypeBox `IsUriTemplate`).
pub(super) fn is_uri_template(value: &str) -> bool {
	URI_TEMPLATE.find(value).is_some()
}

static UUID: LazyLock<Regex> = LazyLock::new(|| pattern(r"^[0-9a-f]{8}-(?:[0-9a-f]{4}-){3}[0-9a-f]{12}$", "i"));

/// A UUID in its hyphenated form (RFC 9562, TypeBox `IsUuid`).
pub(super) fn is_uuid(value: &str) -> bool {
	UUID.find(value).is_some()
}

static JSON_POINTER: LazyLock<Regex> = LazyLock::new(|| pattern(r"^(?:\/(?:[^~/]|~0|~1)*)*$", ""));

/// A JSON Pointer (RFC 6901, TypeBox `IsJsonPointer`).
pub(super) fn is_json_pointer(value: &str) -> bool {
	JSON_POINTER.find(value).is_some()
}

static JSON_POINTER_URI_FRAGMENT: LazyLock<Regex> =
	LazyLock::new(|| pattern(r"^#(?:\/(?:[a-z0-9_\-.!$&'()*+,;:=@]|%[0-9a-f]{2}|~0|~1)*)*$", "i"));

/// A JSON Pointer as a URI fragment (`#/a/b`, TypeBox `IsJsonPointerUriFragment`).
pub(super) fn is_json_pointer_uri_fragment(value: &str) -> bool {
	JSON_POINTER_URI_FRAGMENT.find(value).is_some()
}

static RELATIVE_JSON_POINTER: LazyLock<Regex> =
	LazyLock::new(|| pattern(r"^(?:0|[1-9][0-9]*)(?:#|(?:\/(?:[^~/]|~0|~1)*)*)$", ""));

/// A relative JSON Pointer (TypeBox `IsRelativeJsonPointer`).
pub(super) fn is_relative_json_pointer(value: &str) -> bool {
	RELATIVE_JSON_POINTER.find(value).is_some()
}

static DURATION: LazyLock<Regex> = LazyLock::new(|| {
	pattern(
		concat!(
			r"^P((\d+Y(\d+M(\d+D)?)?|\d+M(\d+D)?|\d+D)(T(\d+H(\d+M(\d+S)?)?|\d+M(\d+S)?|\d+S))?|T(\d+H(\",
			r"d+M(\d+S)?)?|\d+M(\d+S)?|\d+S)|\d+W)$",
		),
		"",
	)
});

/// An ISO 8601 duration (RFC 3339 appendix A, TypeBox `IsDuration`).
pub(super) fn is_duration(value: &str) -> bool {
	DURATION.find(value).is_some()
}

/// An ECMAScript regular expression with the `u` flag (TypeBox `IsRegex`).
pub(super) fn is_regex(value: &str) -> bool {
	Regex::with_flags(value, "u").is_ok()
}

/// `value.normalize("NFC")`.
pub(super) fn nfc(value: &str) -> String {
	icu_normalizer::ComposingNormalizerBorrowed::new_nfc()
		.normalize(value)
		.into_owned()
}
