//! The formats checked by one regular expression each (TypeBox 1.3.27's format checks, MIT), plus `regex`. The
//! sources are TypeBox's, unchanged, run by an ECMAScript regex engine with TypeBox's flags.

use regress::Regex;
use std::sync::LazyLock;

/// A fixed format pattern.
#[expect(
	clippy::expect_used,
	reason = "invariant: the sources are fixed, and the format tests compile each one"
)]
pub(super) fn pattern(source: &str, flags: &str) -> Regex {
	Regex::with_flags(source, flags).expect("a valid format pattern")
}

static EMAIL: LazyLock<Regex> = LazyLock::new(|| {
	pattern(
		concat!(
			r#"^(?:[a-z0-9!#$%&'*+/=?^_`{|}~-]+(?:\.[a-z0-9!#$%&'*+/=?^_`{|}~-]+)*|"(?:[^"\\]|\\[\x20-\x7"#,
			r#"e])*")@(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?)*|"#,
			r#"\[(?:IPv6:[a-f0-9:]+|(?:25[0-5]|2[0-4][0-9]|1[0-9]{2}|[1-9]?[0-9])(?:\.(?:25[0-5]|2[0-4][0"#,
			r#"-9]|1[0-9]{2}|[1-9]?[0-9])){3})\])$"#,
		),
		"i",
	)
});

/// An email address (RFC 5322, TypeBox `IsEmail`).
pub(super) fn is_email(value: &str) -> bool {
	EMAIL.find(value).is_some()
}

static IDN_EMAIL: LazyLock<Regex> = LazyLock::new(|| {
	pattern(
		concat!(
			r#"^(?:[A-Za-z0-9!#$%&'*+/=?^_`{|}~\u{0080}-\u{10FFFF}-]+(?:\.[A-Za-z0-9!#$%&'*+/=?^_`{|}~\u{"#,
			r#"0080}-\u{10FFFF}-]+)*|"(?:[^"\\]|\\.)*")@[\p{L}\p{N}](?:[\p{L}\p{N}-]{0,62})(?<!-)(?:\.[\p"#,
			r#"{L}\p{N}](?:[\p{L}\p{N}-]{0,62})(?<!-))*$"#,
		),
		"iu",
	)
});

/// An internationalized email address (RFC 6531), compared in NFC (TypeBox `IsIdnEmail`).
pub(super) fn is_idn_email(value: &str) -> bool {
	IDN_EMAIL.find(&nfc(value)).is_some()
}

static IPV4: LazyLock<Regex> = LazyLock::new(|| {
	pattern(
		r"^(?:(?:25[0-5]|2[0-4]\d|1\d\d|[1-9]?\d)\.){3}(?:25[0-5]|2[0-4]\d|1\d\d|[1-9]?\d)$",
		"",
	)
});

/// An IPv4 address in dotted-quad form (TypeBox `IsIPv4`).
pub(super) fn is_ipv4(value: &str) -> bool {
	IPV4.find(value).is_some()
}

static IPV6: LazyLock<Regex> = LazyLock::new(|| {
	pattern(
		concat!(
			r"^(?:(?:(?:[0-9a-f]{1,4}:){6}|::(?:[0-9a-f]{1,4}:){5}|(?:[0-9a-f]{1,4})?::(?:[0-9a-f]{1,4}:",
			r"){4}|(?:(?:[0-9a-f]{1,4}:)?[0-9a-f]{1,4})?::(?:[0-9a-f]{1,4}:){3}|(?:(?:[0-9a-f]{1,4}:){0,",
			r"2}[0-9a-f]{1,4})?::(?:[0-9a-f]{1,4}:){2}|(?:(?:[0-9a-f]{1,4}:){0,3}[0-9a-f]{1,4})?::[0-9a-",
			r"f]{1,4}:|(?:(?:[0-9a-f]{1,4}:){0,4}[0-9a-f]{1,4})?::)(?:[0-9a-f]{1,4}:[0-9a-f]{1,4}|(?:(?:",
			r"25[0-5]|2[0-4]\d|1\d\d|[1-9]?\d)\.){3}(?:25[0-5]|2[0-4]\d|1\d\d|[1-9]?\d))|(?:(?:[0-9a-f]{",
			r"1,4}:){0,5}[0-9a-f]{1,4})?::[0-9a-f]{1,4}|(?:(?:[0-9a-f]{1,4}:){0,6}[0-9a-f]{1,4})?::)$",
		),
		"i",
	)
});

/// An IPv6 address (RFC 4291, TypeBox `IsIPv6`).
